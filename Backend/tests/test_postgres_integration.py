"""Opt-in real PostgreSQL API tests; each test owns an isolated temporary schema.

TEST_DATABASE_URL must point to a test database with CREATE SCHEMA permission.
No public tables or existing accounts are read or modified.
"""
import os
import secrets
import unittest
import uuid
from concurrent.futures import ThreadPoolExecutor
from contextlib import ExitStack
from datetime import datetime, timedelta, timezone
from pathlib import Path
from unittest.mock import patch

import psycopg
from psycopg import sql

from app.main import app
from test_auth_route_access import _AsgiClient


@unittest.skipUnless(os.getenv("TEST_DATABASE_URL"), "Set TEST_DATABASE_URL for PostgreSQL integration tests")
class PostgresIntegrationTests(unittest.TestCase):
    def setUp(self):
        self.schema = "tf_test_" + uuid.uuid4().hex
        self.dsn = os.environ["TEST_DATABASE_URL"]
        with psycopg.connect(self.dsn, autocommit=True) as connection:
            connection.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(self.schema)))
        self.addCleanup(self.drop_schema)
        self.stack = ExitStack()
        self.addCleanup(self.stack.close)
        for module in ("app.main", "app.routers.auth", "app.routers.candidates",
                       "app.routers.assessments", "app.routers.invitations", "app.routers.submissions"):
            self.stack.enter_context(patch(module + ".get_connection", side_effect=self.connect))
        with self.connect() as connection:
            connection.execute((Path(__file__).parents[1] / "database" / "schema.sql").read_text())
        self.client = _AsgiClient(app)
        self.employer = self.register_login("employer")
        self.candidate = self.register_login("candidate")
        self.call("POST", "/candidates/me", {}, self.candidate, 201)
        assessment = self.call("POST", "/assessments", {
            "title": "Integration assessment", "description": "A real database check",
            "difficulty": "medium", "duration": 30,
        }, self.employer, 201)
        self.assessment_id = assessment["id"]
        self.call("POST", f"/assessments/{self.assessment_id}/publish", None, self.employer)
        invitation = self.call("POST", f"/assessments/{self.assessment_id}/invitations", {
            "candidate_email": "candidate@example.com",
        }, self.employer, 201)
        self.invitation_id = invitation["id"]
        self.payload = {"token": invitation["invitation_url"].rsplit("/", 1)[1]}

    def connect(self):
        return psycopg.connect(self.dsn, options=f"-c search_path={self.schema}")

    def drop_schema(self):
        # The identifier is generated by this test; never accept a caller's schema.
        with psycopg.connect(self.dsn, autocommit=True) as connection:
            connection.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(self.schema)))

    def call(self, method, path, body=None, token=None, expected=200):
        response = self.client.request(method, path, body, token=token)
        # Avoid printing responses: login and invitation responses contain secrets.
        self.assertEqual(response.status, expected, f"{method} {path}: HTTP {response.status}")
        return response.json

    def register_login(self, role):
        password = secrets.token_urlsafe(24)
        email = f"{role}@example.com"
        self.call("POST", "/register", {
            "full_name": f"Integration {role}", "email": email, "password": password, "role": role,
        }, expected=201)
        return self.call("POST", "/auth/login", {"email": email, "password": password})["access_token"]

    def test_full_workflow_and_concurrent_idempotent_claim(self):
        self.call("POST", "/invitations/validate", self.payload, self.candidate)
        with ThreadPoolExecutor(max_workers=2) as executor:
            claims = list(executor.map(lambda _: self.call(
                "POST", "/invitations/claim", self.payload, self.candidate), range(2)))
        submission_id = claims[0]["submission"]["id"]
        self.assertEqual(submission_id, claims[1]["submission"]["id"])
        resumed = self.call("POST", "/submissions", {"assessment_id": self.assessment_id}, self.candidate)
        self.assertEqual(resumed["id"], submission_id)
        for key, answer in (("task-1", "First answer"), ("task-2", "Second answer")):
            saved = self.call("PATCH", f"/submissions/{submission_id}/answers", {
                "answers": {key: answer},
            }, self.candidate)
        self.assertEqual(saved["answers"], {"task-1": "First answer", "task-2": "Second answer"})
        submitted = self.call("POST", f"/submissions/{submission_id}/submit", token=self.candidate)
        self.assertEqual(submitted["status"], "submitted")
        self.assertIsNotNone(submitted["submitted_at"])
        self.call("POST", "/invitations/claim", self.payload, self.candidate, 409)
        self.call("PATCH", f"/submissions/{submission_id}/answers", {"answers": {}}, self.candidate, 409)
        self.call("POST", f"/submissions/{submission_id}/submit", token=self.candidate, expected=409)
        self.call("GET", f"/submissions/{submission_id}", token=self.employer, expected=403)
        with self.connect() as connection:
            self.assertEqual(connection.execute("SELECT count(*) FROM submissions").fetchone()[0], 1)

    def test_submission_failure_rolls_back_invitation_claim(self):
        with patch("app.routers.invitations.start_submission_for_candidate", side_effect=RuntimeError("injected")):
            self.call("POST", "/invitations/claim", self.payload, self.candidate, 500)
        with self.connect() as connection:
            self.assertEqual(connection.execute(
                "SELECT candidate_id, accepted_at FROM assessment_invitations WHERE id = %s",
                (self.invitation_id,),
            ).fetchone(), (None, None))
            self.assertEqual(connection.execute("SELECT count(*) FROM submissions").fetchone()[0], 0)
        self.call("POST", "/invitations/claim", self.payload, self.candidate)

    def test_invalid_expired_revoked_and_mismatched_tokens_rejected(self):
        for endpoint in ("validate", "claim"):
            self.call("POST", f"/invitations/{endpoint}", {"token": "x" * 43}, self.candidate, 404)
            self.call("POST", f"/invitations/{endpoint}", self.payload, self.employer, 403)
            self.call("POST", f"/invitations/{endpoint}", self.payload, expected=401)
        # Create a second real candidate account through the public API.
        password = secrets.token_urlsafe(24)
        self.call("POST", "/register", {"full_name": "Other Candidate", "email": "other@example.com",
                  "password": password, "role": "candidate"}, expected=201)
        other = self.call("POST", "/auth/login", {"email": "other@example.com", "password": password})["access_token"]
        self.call("POST", "/candidates/me", {}, other, 201)
        self.call("POST", "/invitations/claim", self.payload, other, 404)
        with patch("app.routers.invitations.datetime") as clock:
            clock.now.return_value = datetime.now(timezone.utc) + timedelta(days=8)
            for endpoint in ("validate", "claim"):
                self.call("POST", f"/invitations/{endpoint}", self.payload, self.candidate, 404)
        self.call("POST", f"/assessments/{self.assessment_id}/invitations/{self.invitation_id}/revoke",
                  token=self.employer, expected=204)
        self.call("POST", "/invitations/claim", self.payload, self.candidate, 404)
